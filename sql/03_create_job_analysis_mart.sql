-- =========================================================
-- 求人分析マート
-- mart_job_analysis
-- =========================================================
-- 【このマートの粒度】
-- 1行 = 1求人
--
-- jobsテーブルを基準として、
-- ・求人基本属性
-- ・求人条件
-- ・エントリー数
-- ・応募数
-- ・placement数
-- ・60日以内placement数
-- ・60日以内募集枠充足率
-- を求人単位へ集約する。
--
-- 【主な用途】
-- ・求人活動量の年次比較
-- ・職種 / 求人条件の分布確認
-- ・60日以内募集枠充足率の年次比較
--
-- 【重要】
-- このマートは「求人単位」の分析用。
--
-- 候補者・応募案件単位の
-- ・給与ミスマッチ
-- ・スキルミスマッチ
-- ・推薦
-- ・辞退
-- ・選考リードタイム
--
-- は mart_application_analysis で分析する。
-- =========================================================


-- =========================================================
-- 既存VIEW削除
-- =========================================================
-- CREATE VIEWを再実行できるように、
-- 同名VIEWが存在する場合は先に削除する。
-- 元テーブルのデータを削除する処理ではない。
-- =========================================================

DROP VIEW IF EXISTS mart_job_analysis;


-- =========================================================
-- VIEW作成
-- =========================================================

CREATE VIEW mart_job_analysis AS


-- =========================================================
-- CTE① 求人エントリー集計
-- entry_agg
-- =========================================================
-- job_entriesは
-- 1行 = 1候補者 × 1求人へのエントリー。
--
-- 求人別のエントリー総数を集計する。
-- =========================================================

WITH entry_agg AS (

    SELECT
        job_id,
        COUNT(*) AS entry_count

    FROM job_entries

    GROUP BY
        job_id
),


-- =========================================================
-- CTE② 応募案件集計
-- application_agg
-- =========================================================
-- applicationsは
-- 1行 = 1候補者 × 1求人の正式応募案件。
--
-- 求人別のapplication総数を集計する。
-- =========================================================

application_agg AS (

    SELECT
        job_id,
        COUNT(*) AS application_count

    FROM applications

    GROUP BY
        job_id
),


-- =========================================================
-- CTE③ 就業決定集計
-- placement_agg
-- =========================================================
-- placementsは
-- 1行 = 1最終就業決定。
--
-- applicationsを経由してjob_idを取得し、
-- 求人単位へ集約する。
-- =========================================================

placement_agg AS (

    SELECT
        a.job_id,

        -- ---------------------------------------------
        -- 最終就業決定数
        -- ---------------------------------------------

        COUNT(
            p.placement_id
        ) AS placement_count,


        -- ---------------------------------------------
        -- 求人公開から60日以内のplacement数
        -- ---------------------------------------------
        -- decision_date - open_date <= 60
        -- のplacementを集計する。
        --
        -- 求人自体が60日観察可能かどうかは、
        -- 最終SELECTのjob_60d_observed_flagで
        -- 別途判定する。
        -- ---------------------------------------------

        SUM(
            CASE
                WHEN
                    p.decision_date IS NOT NULL
                    AND
                    (
                        julianday(p.decision_date)
                        -
                        julianday(j.open_date)
                    ) <= 60
                THEN 1
                ELSE 0
            END
        ) AS placement_60d_count


    FROM applications a


    INNER JOIN jobs j
        ON
            a.job_id
            =
            j.job_id


    LEFT JOIN placements p
        ON
            a.application_id
            =
            p.application_id


    GROUP BY
        a.job_id
)


-- =========================================================
-- 最終SELECT
-- =========================================================
-- jobsを起点としてLEFT JOINする。
--
-- そのため、
-- ・エントリー0件
-- ・application 0件
-- ・placement 0件
--
-- の求人もマートから消えない。
-- =========================================================

SELECT

    -- =====================================================
    -- 1. 求人基本情報
    -- =====================================================

    j.job_id,


    -- ---------------------------------------------
    -- 公開年
    -- ---------------------------------------------
    -- 例：
    -- 2025
    -- 2026
    -- ---------------------------------------------

    strftime(
        '%Y',
        j.open_date
    ) AS open_year,


    -- ---------------------------------------------
    -- 公開年月
    -- ---------------------------------------------
    -- 月次・分析対象期間の抽出に利用する。
    --
    -- 例：
    -- 2025-04
    -- ---------------------------------------------

    strftime(
        '%Y-%m',
        j.open_date
    ) AS open_month,


    -- =====================================================
    -- 2. 職種
    -- =====================================================

    o.occupation_name,


    -- =====================================================
    -- 3. 求人条件
    -- =====================================================

    j.required_slots,

    j.offered_hourly_wage,

    j.required_skill_level,

    j.work_style,


    -- =====================================================
    -- 4. 60日観察可能フラグ
    -- =====================================================
    -- 求人公開から60日後までを
    -- DATA_END_DATE内で観察できるか判定する。
    --
    -- 1 = 60日間観察可能
    -- 0 = 右打ち切り
    --
    -- close_dateは判定に使用しない。
    -- =====================================================

    CASE
        WHEN
            date(
                j.open_date,
                '+60 day'
            )
            <=
            date(
                '2026-09-30'
            )
        THEN 1
        ELSE 0
    END AS job_60d_observed_flag,


    -- =====================================================
    -- 5. 求人活動量
    -- =====================================================

    COALESCE(
        e.entry_count,
        0
    ) AS entry_count,


    COALESCE(
        a.application_count,
        0
    ) AS application_count,


    -- =====================================================
    -- 6. placement
    -- =====================================================

    COALESCE(
        p.placement_count,
        0
    ) AS placement_count,


    -- =====================================================
    -- 7. 60日以内placement件数
    -- =====================================================
    -- 60日観察可能求人のみ数値を返す。
    --
    -- 60日未観察求人を0件とすると、
    -- 「60日観察した結果0件」と誤解するため、
    -- 未観察求人はNULLとする。
    -- =====================================================

    CASE
        WHEN
            date(
                j.open_date,
                '+60 day'
            )
            <=
            date(
                '2026-09-30'
            )
        THEN
            COALESCE(
                p.placement_60d_count,
                0
            )
        ELSE NULL
    END AS placement_60d_count,


    -- =====================================================
    -- 8. 60日以内募集枠充足率
    -- =====================================================
    -- 定義：
    --
    -- 60日以内placement数
    -- ----------------------
    -- required_slots
    --
    -- 例：
    -- required_slots = 2
    -- placement_60d_count = 1
    -- → 0.500
    --
    -- 60日未観察求人はNULL。
    --
    -- MIN()により100%を超えないようにし、
    -- NULLIF()により0除算を防止する。
    -- =====================================================

    CASE
        WHEN
            date(
                j.open_date,
                '+60 day'
            )
            <=
            date(
                '2026-09-30'
            )
        THEN
            ROUND(
                1.0
                *
                MIN(
                    COALESCE(
                        p.placement_60d_count,
                        0
                    ),
                    j.required_slots
                )
                /
                NULLIF(
                    j.required_slots,
                    0
                ),
                3
            )
        ELSE NULL
    END AS fill_rate_60d


-- =========================================================
-- 基準テーブル
-- =========================================================

FROM jobs j


-- =========================================================
-- 職種マスタ
-- =========================================================

LEFT JOIN occupations o
    ON
        j.occupation_id
        =
        o.occupation_id


-- =========================================================
-- 求人エントリー集計
-- =========================================================

LEFT JOIN entry_agg e
    ON
        j.job_id
        =
        e.job_id


-- =========================================================
-- application集計
-- =========================================================

LEFT JOIN application_agg a
    ON
        j.job_id
        =
        a.job_id


-- =========================================================
-- placement集計
-- =========================================================

LEFT JOIN placement_agg p
    ON
        j.job_id
        =
        p.job_id
;